package org.lineageos.pcterminal.core.terminal

/**
 * How many cells a code point takes: 0 for combining marks and zero-width formatting, 2 for East
 * Asian wide and fullwidth characters and emoji, 1 for the rest. A compact table, not the full
 * Unicode width data.
 */
object CharWidth {
    private val ZERO = listOf(
        0x0300..0x036F, 0x0483..0x0489, 0x0591..0x05BD, 0x0610..0x061A, 0x064B..0x065F,
        0x0E31..0x0E31, 0x0E34..0x0E3A, 0x0E47..0x0E4E, 0x1AB0..0x1AFF, 0x1DC0..0x1DFF,
        0x200B..0x200F, 0x2028..0x202E, 0x2060..0x2064, 0x20D0..0x20FF, 0xFE00..0xFE0F,
        0xFE20..0xFE2F, 0xFEFF..0xFEFF, 0xE0100..0xE01EF,
    )
    private val WIDE = listOf(
        0x1100..0x115F, 0x231A..0x231B, 0x2329..0x232A, 0x23E9..0x23EC, 0x2614..0x2615,
        0x2648..0x2653, 0x26AA..0x26AB, 0x26BD..0x26BE, 0x26CE..0x26CE, 0x26D4..0x26D4,
        0x26EA..0x26EA, 0x26F2..0x26F5, 0x26FA..0x26FA, 0x26FD..0x26FD, 0x2705..0x2705,
        0x270A..0x270B, 0x2728..0x2728, 0x274C..0x274C, 0x2753..0x2755, 0x2795..0x2797,
        0x2B1B..0x2B1C, 0x2B50..0x2B50, 0x2E80..0x303E, 0x3041..0x33FF, 0x3400..0x4DBF,
        0x4E00..0x9FFF, 0xA000..0xA4CF, 0xAC00..0xD7A3, 0xF900..0xFAFF, 0xFE30..0xFE4F,
        0xFF00..0xFF60, 0xFFE0..0xFFE6, 0x1F004..0x1F004, 0x1F0CF..0x1F0CF, 0x1F18E..0x1F18E,
        0x1F191..0x1F19A, 0x1F200..0x1F251, 0x1F300..0x1F64F, 0x1F680..0x1F6FF, 0x1F7E0..0x1F7EB,
        0x1F900..0x1F9FF, 0x1FA70..0x1FAFF, 0x20000..0x2FFFD, 0x30000..0x3FFFD,
    )

    fun of(codePoint: Int): Int = when {
        codePoint < 0x300 -> 1
        ZERO.any { codePoint in it } -> 0
        WIDE.any { codePoint in it } -> 2
        else -> 1
    }
}
